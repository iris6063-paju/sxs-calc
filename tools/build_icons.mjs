// Extracts the silhouettes used for the recreated standee characters from an Iconify "game-icons" JSON bundle.
// Source art: https://game-icons.net (CC BY 3.0 — Lorc, Delapouite and contributors). See CREDITS.md.
// Usage: node tools/build_icons.mjs <game-icons.json> <out js>
import fs from 'node:fs';
const [, , SRC, OUT] = process.argv;
const j = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const NAMES = `boar unlit-bomb direwolf rabbit wolf-howl spider-alt owl wolf-head praying-mantis stag-head bear-head rock-golem hanging-spider
crab eagle-emblem snake squirrel cactus scorpion dinosaur-rex bull slime cyclops stone-block frog paper-lantern piranha spiral-shell fox
octopus ghost samurai-helmet scarab-beetle carnivorous-plant imp fox-head griffin-symbol harpy wolverine-claws fire-ring cultist turtle
visored-helm sun-priest snail cobra rat hound puppet warlock-hood deer toad-teeth bee eagle-head scarecrow voodoo-doll amphora lion
sprout ogre totem-head cauldron mirror-mirror gorilla djinn monkey oni goat tortoise minotaur robot-golem evil-tree
broadsword wizard-staff templar-shield katana gladius spell-book orb-wand laurel-crown two-handed-sword crystal-wand round-shield`.split(/\s+/).filter(Boolean);
const out = {};
const missing = [];
for (const n of NAMES) {
  const ic = j.icons[n];
  if (!ic) { missing.push(n); continue; }
  const ds = [...ic.body.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) { missing.push(n + '(no path)'); continue; }
  out[n] = ds.join(' ');
}
const js = `// GENERATED by tools/build_icons.mjs. Silhouettes from game-icons.net (CC BY 3.0, Lorc / Delapouite & contributors),\n// recoloured, outlined and animated in js/sprites.js. 512×512 path data.\nexport const ICONS = ${JSON.stringify(out)};\n`;
fs.writeFileSync(OUT, js);
console.log('icons', Object.keys(out).length, 'missing', missing.join(',') || '-', (js.length / 1024).toFixed(1) + ' KB', 'size', j.width, j.height, 'sample', j.icons.boar.body.slice(0, 90));
